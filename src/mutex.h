#ifndef MUTEX_H
#define MUTEX_H

#include <mutex>


class Mutex
{
   // ====== Methods ========================================================
   public:
   Mutex();
   virtual ~Mutex();

   Mutex(const Mutex&) = delete;
   Mutex& operator=(const Mutex&) = delete;

   inline void lock() {
      MyMutex.lock();
   }

   inline void unlock() {
      MyMutex.unlock();
   }

   inline bool try_lock() {
      return MyMutex.try_lock();
   }

   // ====== Private Data ===================================================
   private:
   std::recursive_mutex MyMutex;
};

#endif // MUTEX_H
